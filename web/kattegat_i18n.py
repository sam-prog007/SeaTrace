FRENCH_HINT = re.compile(r"[éèêàùçôîÉÀ«»’]|\b(le|la|les|des|une|un|du|pour|dans|sur|avec|sans|aucun|navire|navires|trajet|trajets|zone|zones)\b")

_ORDERED = sorted(PAIRS, key=lambda p: -len(p[0]))


def _json_forms(text: str):
    """JSON-escaped forms of a string: standard (\\uXXXX for accents) and the HTML-safe variant used by
    Folium, which also escapes ' < > & as \\u0027 \\u003c \\u003e \\u0026."""
    esc = json.dumps(text)[1:-1]
    safe = (esc.replace("'", "\\u0027").replace("<", "\\u003c").replace(">", "\\u003e").replace("&", "\\u0026"))
    return esc, safe


def translate(html: str) -> str:
    for fr, en in _ORDERED:
        html = html.replace(fr, en)
        (fe, fs), (ee, es) = _json_forms(fr), _json_forms(en)
        if fe != fr:
            html = html.replace(fe, ee)
        if fs != fe:
            html = html.replace(fs, es)
    for rx, rep in REGEX:
        html = rx.sub(rep, html)
    return html


@lru_cache(maxsize=4)
def _translated(path: str, mtime: float) -> str:
    return translate(Path(path).read_text(encoding="utf-8"))


def translate_file(path: Path) -> str:
    return _translated(str(path), path.stat().st_mtime)


def leftover_french(html: str, width=70, limit=60):
    """Lines of the translated page that still look French (to complete PAIRS)."""
    out = []
    for line in html.split("\n"):
        if FRENCH_HINT.search(line) and len(line) < 5000 and "base64" not in line:
            for m in re.finditer(r"[^<>{};=\"`]*(?:[éèêàùçôîÉÀ«»’]|\b(?:le|la|les|des|une|du|pour|dans|sur|avec|sans|aucun|navires?|trajets?)\b)[^<>{};=\"`]*", line):
                out.append(m.group(0).strip()[:width * 2])
    seen, res = set(), []
    for x in out:
        if x and x not in seen:
            seen.add(x)
            res.append(x)
    return res[:limit]
